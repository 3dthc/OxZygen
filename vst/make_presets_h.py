#!/usr/bin/env python3
"""presets.json -> presets_tab.h, the preset table engine.c applies itself (the browser, prev / next, program changes).

    python3 vst/make_presets_h.py          (vst/build.sh and the release build run it too; the header is committed)

Values become what set_param() would get: an option's index, or the number in the parameter's own units.
A preset's category is its name's prefix (VOX, WND, ...); "Init" has none and is listed under ALL only."""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
CATS = ["VOX", "WND", "BRS", "STR", "BEL", "SYN", "AIR"]   # the browser's order: Voices, Winds, Brass, Strings, Bells, Synth, Air


def value(p, v, where):
    opts = [str(o) for o in p.get("options") or []]
    if opts:
        low = [o.lower() for o in opts]
        if isinstance(v, str) and v.lower() in low:
            return low.index(v.lower())
        if isinstance(v, int) and 0 <= v < len(opts):
            return v
        sys.exit("%s: %s=%r is not one of %s" % (where, p["key"], v, ",".join(opts)))
    lo, hi = p.get("min", 0), p.get("max", 1)
    if isinstance(v, bool) or not isinstance(v, (int, float)) or not lo <= v <= hi:
        sys.exit("%s: %s=%r is not a number in %g..%g" % (where, p["key"], v, lo, hi))
    return v


def main():
    params = {p["key"]: p for p in json.load(open(os.path.join(HERE, "params.json")))["params"]}
    presets = json.load(open(os.path.join(HERE, "presets.json")))["presets"]
    names = [p["name"] for p in presets]
    if params["preset"]["options"] != names:
        sys.exit("params.json: preset's options must be presets.json's names, in order")
    keys = []
    for pr in presets:
        for k in pr["values"]:
            if k not in params:
                sys.exit("presets.json: %r: %r is not a parameter" % (pr["name"], k))
            if k not in keys:
                keys.append(k)
    out = ["/* generated by make_presets_h.py from presets.json: edit that, not this file */",
           "#define NPRESET %d" % len(presets), "#define NPRESET_KEYS %d" % len(keys),
           "static const char *const PRESET_KEYS[NPRESET_KEYS] = {%s};" % ", ".join('"%s"' % k for k in keys),
           "static const char *const PRESET_NAME[NPRESET] = {%s};" % ", ".join(json.dumps(n) for n in names),
           "/* -1: no category (Init); else an index into the browser's categories */",
           "static const signed char PRESET_CAT[NPRESET] = {%s};"
           % ", ".join(str(CATS.index(n.split()[0])) if n.split()[0] in CATS else "-1" for n in names),
           "/* NAN: the preset leaves that parameter as it is */",
           "static const float PRESET_VAL[NPRESET][NPRESET_KEYS] = {"]
    for pr in presets:
        row = []
        for k in keys:
            row.append("%g" % value(params[k], pr["values"][k], pr["name"]) if k in pr["values"] else "NAN")
        out.append("    {%s}," % ", ".join(row))
    out.append("};")
    open(os.path.join(HERE, "presets_tab.h"), "w").write("\n".join(out) + "\n")
    print("presets_tab.h: %d presets, %d keys" % (len(presets), len(keys)))


if __name__ == "__main__":
    main()
